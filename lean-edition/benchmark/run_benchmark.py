#!/usr/bin/env python3
"""Compare compile times of the NOVAthesis template and the lean edition.

The same synthetic thesis content (6 chapters with sections, tables, figures,
citations and acronyms, about 60 references) is put into:

  novathesis   the NOVAthesis template from "NOVAthesis 2025-2026.zip"
  lean         the lean edition, default references (apacite, BibTeX)
  lean-apa7    the lean edition with the apa7 option (biblatex-apa, Biber)

For each variant the script measures
  full build   latexmk -pdf from a clean folder (all passes, BibTeX/Biber,
               glossaries), repeated RUNS times
  one pass     one more pdflatex run on the finished build, repeated RUNS times
and writes results.md and results.csv next to this script.

Usage (from the repository root):
  python3 lean-edition/benchmark/run_benchmark.py [--runs 3]

Requirements: TeX Live with latexmk, pdflatex, bibtex, biber and makeindex.
The content is generated by this script, so no thesis text is stored here.
"""
import argparse
import csv
import os
import platform
import random
import re
import shutil
import statistics
import subprocess
import time
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.dirname(HERE)
ROOT = os.path.dirname(LEAN)
NOVA_ZIP = os.path.join(ROOT, 'NOVAthesis 2025-2026.zip')
RUNS_DIR = os.path.join(HERE, 'runs')

# ---------------------------------------------------------------------------
# Synthetic content (identical text for all variants)
# ---------------------------------------------------------------------------
WORDS = ('spatial analysis data suitability criteria model weight layer raster '
         'energy water climate grid land network region site carbon '
         'evaluation method result sensitivity uncertainty policy planning '
         'infrastructure distribution location index value surface scale '
         'standardisation aggregation constraint scenario indicator decision').split()
ACRONYMS = [('GIS', 'Geographic information systems'), ('MCDA', 'Multi-criteria decision analysis'),
            ('AHP', 'Analytic hierarchy process'), ('WLC', 'Weighted linear combination'),
            ('OWA', 'Ordered weighted averaging'), ('DEM', 'Digital elevation model'),
            ('CRS', 'Coordinate reference system'), ('PUE', 'Power usage effectiveness'),
            ('SDG', 'Sustainable Development Goal'), ('EU', 'European Union'),
            ('LULC', 'Land use and land cover'), ('API', 'Application programming interface')]
N_REFS = 60


def sentence(rng, n=None):
    n = n or rng.randint(12, 24)
    w = [rng.choice(WORDS) for _ in range(n)]
    return w[0].capitalize() + ' ' + ' '.join(w[1:]) + '.'


def paragraph(rng, keys, acr):
    parts = []
    for i in range(rng.randint(5, 8)):
        s = sentence(rng)
        r = rng.random()
        if r < 0.25:
            s = s[:-1] + ' \\parencite{%s}.' % rng.choice(keys)
        elif r < 0.35:
            s = '\\textcite{%s} report that %s' % (rng.choice(keys), s[0].lower() + s[1:])
        elif r < 0.5:
            s = s[:-1] + ' using \\gls{%s}.' % rng.choice(acr)
        parts.append(s)
    return ' '.join(parts)


def chapter(rng, num, keys, acr):
    title = ['Introduction', 'Literature Review', 'Data and Methodology',
             'Results', 'Discussion', 'Conclusion'][num - 1]
    out = ['\\chapter{%s}\\label{ch:bench%d}' % (title, num), '']
    for sec in range(1, 5):
        out += ['\\section{%s}' % sentence(rng, 4)[:-1], '']
        for _ in range(3):
            out += [paragraph(rng, keys, acr), '']
        if sec == 2:
            out += ['\\begin{table}[htbp]', '\\centering',
                    '\\caption{%s}\\label{tab:b%d}' % (sentence(rng, 8)[:-1], num),
                    '\\begin{tabular}{llrr}', '\\toprule',
                    'Criterion & Source & Weight & Score \\\\', '\\midrule']
            for _ in range(6):
                out.append('%s & %s & %.2f & %.1f \\\\' % (rng.choice(WORDS), rng.choice(WORDS),
                                                         rng.random(), rng.random() * 100))
            out += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
        if sec == 3:
            out += ['\\begin{figure}[htbp]', '\\centering',
                    '\\includegraphics[width=0.6\\textwidth]{bench-figure}',
                    '\\caption{%s}\\label{fig:b%d}' % (sentence(rng, 8)[:-1], num),
                    '\\end{figure}', '']
            out += ['\\begin{equation}', 'S_i = \\sum_{j=1}^{n} w_j \\, x_{ij}', '\\end{equation}', '']
    return '\n'.join(out) + '\n'


def bibliography(rng):
    entries = []
    for k in range(1, N_REFS + 1):
        n_auth = rng.choice([1, 2, 3, 4, 6, 9])
        authors = ' and '.join('%s, %s.' % (rng.choice(['Silva', 'Costa', 'Schmidt', 'Murphy', 'Dubois',
                                                        'Jansen', 'Garcia', 'Rossi', 'Novak', 'Kim']) + str(k % 7),
                                            rng.choice('ABCDEFGHJKLMNPRST'))
                               for _ in range(n_auth))
        entries.append('@article{ref%02d,\n  author  = {%s},\n  title   = {%s},\n'
                       '  journal = {Journal of %s Studies},\n  volume  = {%d},\n  pages   = {%d--%d},\n'
                       '  year    = {%d},\n  doi     = {10.0000/bench.%04d}\n}\n'
                       % (k, authors, sentence(rng, 9)[:-1], rng.choice(WORDS).capitalize(),
                          rng.randint(1, 60), 10 * k, 10 * k + 15, rng.randint(2000, 2026), k))
    return '\n'.join(entries)


def figure_png(path):
    """A plain 600 x 400 grey test image (written without extra libraries)."""
    import struct
    import zlib
    w, h = 600, 400
    raw = b''.join(b'\x00' + bytes([200, 200, 200]) * w for _ in range(h))

    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    png = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
           + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    open(path, 'wb').write(png)


def content():
    rng = random.Random(2026)
    keys = ['ref%02d' % k for k in range(1, N_REFS + 1)]
    acr = [a for a, _ in ACRONYMS]
    chapters = [chapter(rng, i, keys, acr) for i in range(1, 7)]
    appendix = '\\chapter{Supplementary Material}\n\n' + paragraph(rng, keys, acr) + '\n'
    abstract = paragraph(rng, keys[:1], acr).split('\\')[0]
    return chapters, appendix, bibliography(rng), abstract


# ---------------------------------------------------------------------------
# Variants
# ---------------------------------------------------------------------------
def setup_novathesis(dest, chapters, appendix, bib, abstract):
    with zipfile.ZipFile(NOVA_ZIP) as z:
        z.extractall(dest)
    ch = os.path.join(dest, 'Chapters')
    for i, c in enumerate(chapters, 1):
        open(os.path.join(ch, 'bench%d.tex' % i), 'w').write(c)
    open(os.path.join(ch, 'benchappendix.tex'), 'w').write(appendix)
    open(os.path.join(ch, 'acronyms.tex'), 'w').write(
        ''.join('\\newacronym{%s}{%s}{%s}\n' % (a, a, d) for a, d in ACRONYMS))
    for lang in ('en', 'pt'):
        open(os.path.join(ch, 'abstract-%s.tex' % lang), 'w').write(abstract + '\n')
    open(os.path.join(ch, 'acknowledgements.tex'), 'w').write(abstract + '\n')
    open(os.path.join(dest, 'Bibliography', 'bench.bib'), 'w').write(bib)
    figure_png(os.path.join(ch, 'Figures', 'bench-figure.png'))
    files = ['\\ntaddfile{bib}{bench.bib}', '\\ntaddfile{acknowledgements}{acknowledgements}',
             '\\ntaddfile{abstract}[pt]{abstract-pt}', '\\ntaddfile{abstract}[en]{abstract-en}',
             '\\ntaddfile{glossaries}[acronym]{acronyms}']
    files += ['\\ntaddfile{chapter}{bench%d}' % i for i in range(1, 7)]
    files += ['\\ntaddfile{appendix}{benchappendix}']
    open(os.path.join(dest, 'Config', '4_files.tex'), 'w').write('\n'.join(files) + '\n')
    # Submission version of a Geospatial Technologies dissertation
    cfg = os.path.join(dest, 'Config', '1_novathesis.tex')
    s = open(cfg).read()
    s = s.replace('\\ntsetup{docstatus=working}', '\\ntsetup{docstatus=provisional}')
    s = re.sub(r'\\newcommand\{\\imsDegree\}\{[^}]*\}', r'\\newcommand{\\imsDegree}{mgt}', s)
    s = re.sub(r'\\newcommand\{\\imsSpecialization\}\{[^}]*\}', r'\\newcommand{\\imsSpecialization}{main}', s)
    open(cfg, 'w').write(s)
    return 'template.tex'


def setup_lean(dest, chapters, appendix, bib, abstract, apa7=False):
    build = ('.aux', '.log', '.bbl', '.blg', '.bcf', '.run.xml', '.toc', '.lof', '.lot', '.out',
             '.fls', '.fdb_latexmk', '.pdf', '.synctex.gz')

    def ignore(folder, names):
        skip = {n for n in names if n in ('benchmark', 'preview')}
        if os.path.abspath(folder) == LEAN:
            skip |= {n for n in names if n.startswith('main.') and n.endswith(build)}
        skip |= {n for n in names if n.endswith('.aux')}
        return skip
    shutil.copytree(LEAN, dest, ignore=ignore, dirs_exist_ok=True)
    ch = os.path.join(dest, 'Chapters')
    for f in os.listdir(ch):
        os.remove(os.path.join(ch, f))
    for i, c in enumerate(chapters, 1):
        open(os.path.join(ch, 'bench%d.tex' % i), 'w').write(c)
    open(os.path.join(dest, 'Appendices', 'appendix-a.tex'), 'w').write(appendix)
    open(os.path.join(dest, 'Bibliography', 'references.bib'), 'w').write(bib)
    for f, head in (('abstract-en', 'Abstract'), ('acknowledgements', 'Acknowledgements')):
        open(os.path.join(dest, 'FrontMatter', f + '.tex'), 'w').write(
            '\\frontchapter{%s}\n\n%s\n' % (head, abstract))
    open(os.path.join(dest, 'FrontMatter', 'acronyms.tex'), 'w').write(
        '\\frontchapter{List of Acronyms and Abbreviations}\n\\begin{acronymlist}\n'
        + ''.join('\\acronym{%s}{%s}\n' % (a, d) for a, d in ACRONYMS) + '\\end{acronymlist}\n')
    figure_png(os.path.join(dest, 'Figures', 'bench-figure.png'))
    m = os.path.join(dest, 'main.tex')
    s = open(m).read()
    if apa7:
        s = s.replace('\\documentclass{novaims-thesis}', '\\documentclass[apa7]{novaims-thesis}')
    # Same citation and acronym commands as the NOVAthesis content
    extra = '\\input{thesis-info}\n\\providecommand{\\textcite}{\\citet}\\providecommand{\\parencite}{\\citep}\n' \
            '\\newcommand{\\gls}[1]{#1}\n'
    s = s.replace('\\input{thesis-info}\n', extra)
    s = re.sub(r'\\include\{Chapters/[^}]*\}\n', '', s)
    s = s.replace('\\mainmatter\n\\pagestyle{novaims}\n',
                  '\\mainmatter\n\\pagestyle{novaims}\n' + ''.join('\\include{Chapters/bench%d}\n' % i for i in range(1, 7)))
    s = s.replace('\\makededication{FrontMatter/dedication}', '')
    open(m, 'w').write(s)
    # Same cover programme as the NOVAthesis run
    t = os.path.join(dest, 'thesis-info.tex')
    s = open(t).read()
    s = re.sub(r'^\\covercode\{[^}]*\}', r'\\covercode{MGT-EN}', s, flags=re.M)
    s = re.sub(r'^\\programme\{[^\n]*\}$', r'\\programme{Geospatial Technologies}', s, flags=re.M)
    open(t, 'w').write(s)
    return 'main.tex'


def timed(cmd, cwd):
    t = time.perf_counter()
    r = subprocess.run(cmd, cwd=cwd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return time.perf_counter() - t, r.returncode


def pages(pdf):
    out = subprocess.run(['pdfinfo', pdf], capture_output=True, text=True).stdout
    m = re.search(r'Pages:\s+(\d+)', out)
    return int(m.group(1)) if m else 0


def version(cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True).stdout.splitlines()[0].strip()
    except (OSError, IndexError):
        return 'not found'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runs', type=int, default=3)
    args = ap.parse_args()
    chapters, appendix, bib, abstract = content()
    variants = [('novathesis', setup_novathesis, {}), ('lean', setup_lean, {}),
                ('lean-apa7', setup_lean, {'apa7': True})]
    rows = []
    shutil.rmtree(RUNS_DIR, ignore_errors=True)
    for name, setup, kw in variants:
        full, single, pg, ok = [], [], 0, True
        for r in range(args.runs):
            d = os.path.join(RUNS_DIR, '%s-%d' % (name, r))
            os.makedirs(d)
            main_tex = setup(d, chapters, appendix, bib, abstract, **kw)
            t, rc = timed(['latexmk', '-pdf', '-interaction=nonstopmode', main_tex], d)
            ok = ok and rc == 0
            full.append(t)
            pg = pages(os.path.join(d, main_tex.replace('.tex', '.pdf')))
            t, rc = timed(['pdflatex', '-interaction=nonstopmode', main_tex], d)
            single.append(t)
            print('%-11s run %d: full build %.1f s, one pass %.1f s, %d pages%s'
                  % (name, r + 1, full[-1], single[-1], pg, '' if ok else ' (latexmk reported errors)'))
        rows.append({'variant': name, 'full_build_s': round(statistics.median(full), 1),
                     'one_pass_s': round(statistics.median(single), 1), 'pages': pg,
                     'runs': args.runs, 'latexmk_ok': ok})
    env = [('pdfTeX', version(['pdflatex', '--version'])), ('Biber', version(['biber', '--version'])),
           ('BibTeX', version(['bibtex', '--version'])), ('latexmk', version(['latexmk', '--version'])),
           ('OS', platform.platform()), ('CPU', platform.processor() or platform.machine()),
           ('CPU cores', str(os.cpu_count()))]
    try:
        for line in open('/proc/cpuinfo'):
            if line.startswith('model name'):
                env[5] = ('CPU', line.split(':', 1)[1].strip())
                break
    except OSError:
        pass
    with open(os.path.join(HERE, 'results.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(HERE, 'results.md'), 'w') as f:
        f.write('# Benchmark results\n\nMedian of %d runs per variant. Engine: pdfLaTeX.\n\n' % args.runs)
        f.write('| Variant | Full build (s) | One pass (s) | Pages | latexmk OK |\n| --- | --- | --- | --- | --- |\n')
        for r in rows:
            f.write('| %s | %.1f | %.1f | %d | %s |\n' % (r['variant'], r['full_build_s'], r['one_pass_s'],
                                                       r['pages'], 'yes' if r['latexmk_ok'] else 'no'))
        f.write('\n## Environment\n\n')
        for k, v in env:
            f.write('- %s: %s\n' % (k, v))
    print(open(os.path.join(HERE, 'results.md')).read())


if __name__ == '__main__':
    main()
